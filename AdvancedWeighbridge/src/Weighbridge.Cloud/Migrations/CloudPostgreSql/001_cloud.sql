-- AWMS cloud server schema (PostgreSQL – production).
-- Same conventions as the site database: ISO-8601 UTC text timestamps, integer grams, GUID text uids.

CREATE TABLE sites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL,
    name TEXT NOT NULL,
    key_hash TEXT NOT NULL UNIQUE,
    key_prefix TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_utc TEXT NOT NULL,
    last_heartbeat_utc TEXT,
    app_version TEXT,
    heartbeat_json TEXT,
    offline_notified BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE cloud_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    display_name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    mfa_secret TEXT,
    mfa_last_step BIGINT,
    failed_attempts BIGINT NOT NULL DEFAULT 0,
    locked_until_utc TEXT,
    last_login_utc TEXT,
    created_utc TEXT NOT NULL
);

CREATE TABLE cloud_user_sites (
    user_id BIGINT NOT NULL REFERENCES cloud_users(id) ON DELETE CASCADE,
    site_id BIGINT NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, site_id)
);

CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES cloud_users(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    family TEXT NOT NULL,
    expires_utc TEXT NOT NULL,
    created_utc TEXT NOT NULL,
    revoked_utc TEXT,
    replaced BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_refresh_family ON refresh_tokens(family);

CREATE TABLE cloud_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL REFERENCES sites(id),
    uid TEXT NOT NULL UNIQUE,
    ticket_no TEXT NOT NULL,
    version BIGINT NOT NULL,
    status TEXT NOT NULL,
    vehicle_reg TEXT NOT NULL,
    vehicle_norm TEXT NOT NULL,
    customer_name TEXT,
    supplier_name TEXT,
    material_name TEXT,
    gross_g BIGINT,
    tare_g BIGINT,
    net_g BIGINT,
    has_manual BOOLEAN NOT NULL DEFAULT FALSE,
    operating_mode TEXT NOT NULL,
    created_utc TEXT NOT NULL,
    completed_utc TEXT,
    payload_json TEXT NOT NULL,
    payload_hash TEXT NOT NULL,
    received_utc TEXT NOT NULL
);
CREATE INDEX ix_ctx_site_created ON cloud_transactions(site_id, created_utc);
CREATE INDEX ix_ctx_completed ON cloud_transactions(completed_utc);
CREATE INDEX ix_ctx_vehicle ON cloud_transactions(vehicle_norm);
CREATE INDEX ix_ctx_status ON cloud_transactions(status, created_utc);

CREATE TABLE sync_conflicts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL REFERENCES sites(id),
    entity_type TEXT NOT NULL,
    uid TEXT NOT NULL,
    local_version BIGINT,
    server_version BIGINT,
    payload_json TEXT,
    at_utc TEXT NOT NULL
);

CREATE TABLE cloud_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL REFERENCES sites(id),
    uid TEXT NOT NULL UNIQUE,
    local_id BIGINT NOT NULL,
    at_utc TEXT NOT NULL,
    username TEXT NOT NULL,
    machine TEXT,
    category TEXT NOT NULL,
    action TEXT NOT NULL,
    entity_type TEXT,
    entity_id TEXT,
    summary TEXT NOT NULL,
    reason TEXT,
    prev_hash TEXT NOT NULL,
    hash TEXT NOT NULL,
    received_utc TEXT NOT NULL
);
CREATE INDEX ix_caudit_site ON cloud_audit_events(site_id, local_id);
CREATE INDEX ix_caudit_at ON cloud_audit_events(at_utc);

CREATE TABLE cloud_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT NOT NULL REFERENCES sites(id),
    uid TEXT NOT NULL UNIQUE,
    at_utc TEXT NOT NULL,
    severity TEXT NOT NULL,
    category TEXT NOT NULL,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    entity_type TEXT,
    entity_id TEXT,
    received_utc TEXT NOT NULL
);
CREATE INDEX ix_cnotif_at ON cloud_notifications(at_utc);

CREATE TABLE notification_reads (
    user_id BIGINT NOT NULL REFERENCES cloud_users(id) ON DELETE CASCADE,
    notification_id BIGINT NOT NULL REFERENCES cloud_notifications(id),
    PRIMARY KEY (user_id, notification_id)
);

CREATE TABLE site_users (
    site_id BIGINT NOT NULL REFERENCES sites(id),
    username TEXT NOT NULL,
    display_name TEXT NOT NULL,
    role TEXT NOT NULL,
    is_active BOOLEAN NOT NULL,
    last_login_utc TEXT,
    updated_utc TEXT NOT NULL,
    PRIMARY KEY (site_id, username)
);

CREATE TABLE commands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid TEXT NOT NULL UNIQUE,
    site_id BIGINT NOT NULL REFERENCES sites(id),
    type TEXT NOT NULL,
    target_uid TEXT,
    reason TEXT,
    requested_by TEXT NOT NULL,
    requested_utc TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Pending',
    result_message TEXT,
    delivered_utc TEXT,
    completed_utc TEXT
);
CREATE INDEX ix_commands_site ON commands(site_id, status);

CREATE TABLE server_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at_utc TEXT NOT NULL,
    username TEXT NOT NULL,
    action TEXT NOT NULL,
    detail TEXT NOT NULL,
    ip TEXT
);
CREATE INDEX ix_server_audit_at ON server_audit(at_utc);

-- Case-insensitive uniqueness (SQLite uses COLLATE NOCASE).
CREATE UNIQUE INDEX ux_sites_code_ci ON sites (lower(code));
CREATE UNIQUE INDEX ux_cloud_users_username_ci ON cloud_users (lower(username));
