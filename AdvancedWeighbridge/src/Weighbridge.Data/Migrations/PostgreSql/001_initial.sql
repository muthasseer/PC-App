-- Advanced Weighbridge Management System – initial schema (PostgreSQL 14+).
-- Same design as the SQLite schema: timestamps are ISO-8601 UTC text (yyyy-MM-ddTHH:mm:ss.fffZ, sortable),
-- weights are BIGINT grams, uid columns are GUID text used for cloud synchronisation.

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    is_system BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE role_permissions (
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission TEXT NOT NULL,
    PRIMARY KEY (role_id, permission)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid TEXT NOT NULL UNIQUE,
    username TEXT NOT NULL,
    display_name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role_id BIGINT NOT NULL REFERENCES roles(id),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    mfa_secret_protected TEXT,
    mfa_last_step BIGINT,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until_utc TEXT,
    last_login_utc TEXT,
    password_changed_utc TEXT,
    created_utc TEXT NOT NULL,
    updated_utc TEXT NOT NULL
);

CREATE TABLE login_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    username TEXT NOT NULL,
    success BOOLEAN NOT NULL,
    reason TEXT,
    machine TEXT,
    at_utc TEXT NOT NULL
);
CREATE INDEX ix_login_history_at ON login_history(at_utc);

