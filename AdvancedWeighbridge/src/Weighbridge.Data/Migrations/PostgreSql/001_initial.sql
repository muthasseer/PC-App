CREATE FUNCTION awms_transaction_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'weighment_transactions cannot be deleted; cancel them instead';
    END IF;
    IF OLD.status = 'Cancelled' THEN
        RAISE EXCEPTION 'a cancelled transaction cannot be modified';
    END IF;
    IF OLD.status = 'Completed' AND (
        NEW.gross_g IS DISTINCT FROM OLD.gross_g OR NEW.tare_g IS DISTINCT FROM OLD.tare_g OR NEW.net_g IS DISTINCT FROM OLD.net_g OR
        NEW.first_g IS DISTINCT FROM OLD.first_g OR NEW.second_g IS DISTINCT FROM OLD.second_g OR
        NEW.first_measurement_id IS DISTINCT FROM OLD.first_measurement_id OR NEW.second_measurement_id IS DISTINCT FROM OLD.second_measurement_id) THEN
        RAISE EXCEPTION 'weights of a completed transaction cannot be changed';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_txn_guard BEFORE UPDATE OR DELETE ON weighment_transactions FOR EACH ROW EXECUTE FUNCTION awms_transaction_guard();
