CREATE TABLE weighment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid TEXT NOT NULL UNIQUE,
    ticket_no TEXT NOT NULL UNIQUE,
    site_id BIGINT NOT NULL REFERENCES sites(id),
    weighbridge_id BIGINT NOT NULL REFERENCES weighbridges(id),
    status TEXT NOT NULL CHECK (status IN ('Pending', 'Completed', 'Cancelled')),
    direction TEXT NOT NULL CHECK (direction IN ('Inbound', 'Outbound', 'Internal')),
    operating_mode TEXT NOT NULL,
    vehicle_id BIGINT REFERENCES vehicles(id),
    vehicle_reg TEXT NOT NULL,
    vehicle_reg_norm TEXT NOT NULL,
    driver_id BIGINT REFERENCES drivers(id),
    driver_name TEXT,
    transport_company_id BIGINT REFERENCES transport_companies(id),
    customer_id BIGINT REFERENCES customers(id),
    customer_name TEXT,
    supplier_id BIGINT REFERENCES suppliers(id),
    supplier_name TEXT,
    material_id BIGINT REFERENCES materials(id),
    material_name TEXT,
    order_id BIGINT REFERENCES orders(id),
    delivery_note_no TEXT,
    reference_no TEXT,
    remarks TEXT,
    replaces_transaction_id BIGINT REFERENCES weighment_transactions(id),
    first_measurement_id BIGINT,
    second_measurement_id BIGINT,
    first_g BIGINT,
    second_g BIGINT,
    gross_g BIGINT,
    tare_g BIGINT,
    net_g BIGINT,
    first_is_gross BOOLEAN,
    tare_method TEXT,
    has_manual_weight BOOLEAN NOT NULL DEFAULT FALSE,
    has_override BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT NOT NULL REFERENCES users(id),
    created_utc TEXT NOT NULL,
    completed_by BIGINT REFERENCES users(id),
    completed_utc TEXT,
    cancelled_by BIGINT REFERENCES users(id),
    cancelled_utc TEXT,
    cancel_reason TEXT,
    updated_utc TEXT NOT NULL,
    version INTEGER NOT NULL DEFAULT 1,
    CHECK (status <> 'Completed' OR (gross_g IS NOT NULL AND tare_g IS NOT NULL AND net_g IS NOT NULL AND completed_utc IS NOT NULL)),
    CHECK (status <> 'Cancelled' OR (cancel_reason IS NOT NULL AND cancelled_utc IS NOT NULL))
);
