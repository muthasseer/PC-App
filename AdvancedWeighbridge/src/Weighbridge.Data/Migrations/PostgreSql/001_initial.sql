-- ---------------------------------------------------------------- immutability
CREATE FUNCTION awms_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% are immutable', TG_TABLE_NAME;
END;
$$;

CREATE TRIGGER trg_measurements_immutable BEFORE UPDATE OR DELETE ON weight_measurements FOR EACH ROW EXECUTE FUNCTION awms_immutable();
